"""重新打包 / 校验 ShellMate 开发交接包。零第三方依赖。

用法（在包根目录下）：
    python pack.py             # 生成 MANIFEST.sha256 + 上级目录的 <目录名>.zip
    python pack.py --verify    # 按 MANIFEST.sha256 校验当前目录是否完整

说明：zip 内保留一个顶层目录，解压后可直接作为工作区打开。
     临时产物（__pycache__ / .localdata / *.pyc / .DS_Store / Thumbs.db）一律不打包。
"""

from __future__ import annotations

import argparse
import hashlib
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MANIFEST = ROOT / "MANIFEST.sha256"
ZIP_PATH = ROOT.parent / f"{ROOT.name}.zip"

EXCLUDE_DIRS = frozenset({"__pycache__", ".localdata", ".git", ".pytest_cache", ".mypy_cache"})
EXCLUDE_NAMES = frozenset({"MANIFEST.sha256", ".DS_Store", "Thumbs.db"})


def iter_files():
    """产出 (绝对路径, zip 内相对路径)，按路径排序保证可复现。"""
    for path in sorted(ROOT.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(ROOT)
        if any(part in EXCLUDE_DIRS for part in rel.parts):
            continue
        if path.name in EXCLUDE_NAMES or path.suffix == ".pyc":
            continue
        yield path, rel.as_posix()


def digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 256), b""):
            h.update(chunk)
    return h.hexdigest()


def write_manifest(files: list[tuple[Path, str]]) -> None:
    lines = [f"{digest(path)}  {rel}" for path, rel in files]
    lines.append(f"# {len(lines)} files · generated by pack.py")
    MANIFEST.write_text("\n".join(lines) + "\n", encoding="utf-8")


def pack() -> int:
    files = list(iter_files())
    write_manifest(files)
    entries = files + [(MANIFEST, MANIFEST.name)]
    with zipfile.ZipFile(ZIP_PATH, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for path, rel in entries:
            zf.write(path, arcname=f"{ROOT.name}/{rel}")
    size_kb = ZIP_PATH.stat().st_size / 1024
    print(f"PACK OK  {len(entries)} files  ->  {ZIP_PATH.name}  ({size_kb:.0f} KB)")
    return 0


def verify() -> int:
    if not MANIFEST.exists():
        print("VERIFY FAIL  缺少 MANIFEST.sha256，请先运行 python pack.py")
        return 1
    expected: dict[str, str] = {}
    for line in MANIFEST.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        checksum, _, rel = line.partition("  ")
        expected[rel.strip()] = checksum.strip()

    current = {rel: digest(path) for path, rel in iter_files()}
    problems: list[str] = []
    for rel, checksum in expected.items():
        if rel not in current:
            problems.append(f"MISSING  {rel}")
        elif current[rel] != checksum:
            problems.append(f"CHANGED  {rel}")
    added = sorted(set(current) - set(expected))

    if problems:
        for item in problems:
            print(item)
        print(f"VERIFY FAIL  {len(problems)} 项不一致")
        return 1
    print(f"VERIFY OK  {len(expected)} files 全部匹配")
    if added:
        print(f"新增文件（未入清单，属正常继续开发）：{len(added)} 个")
        for rel in added[:10]:
            print(f"  + {rel}")
        if len(added) > 10:
            print(f"  ... 另有 {len(added) - 10} 个")
        print("提示：运行 python pack.py 可重新生成清单与 zip。")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="打包 / 校验 ShellMate 交接包")
    parser.add_argument("--verify", action="store_true", help="校验而不打包")
    args = parser.parse_args()
    return verify() if args.verify else pack()


if __name__ == "__main__":
    raise SystemExit(main())
